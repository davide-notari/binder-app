"""
make_premultiply_fixture.py: writes src/dev/premultiply-fixture.ts, a tiny synthetic lossless WebP with known
semi-transparent texels (RENDERING.md §2). The app uploads it with premultiplication and reads it back; every
texel must equal round(c * a / 255), the premultiplication used by the reference renderer.

  python3 tools/make_premultiply_fixture.py
Requires: Python 3.9+, pillow, numpy.
"""
import base64, io, json, os
import numpy as np
from PIL import Image

W, H = 16, 16
rng = np.random.default_rng(20261019)
rgba = rng.integers(0, 256, size=(H, W, 4), dtype=np.uint8)
# alpha values where rounding mistakes show up first, then random ones
special = [0, 1, 2, 3, 4, 127, 128, 129, 191, 192, 253, 254, 255]
flat = rgba.reshape(-1, 4)
flat[: len(special) * 8, 3] = np.repeat(special, 8)
flat[: len(special) * 8 : 2, :3] = 255  # brightest colour at every special alpha
flat[1 : len(special) * 8 : 4, :3] = 1
flat[flat[:, 3] == 0, :3] = 0  # transparent texels: colour is not preserved by lossless WebP (exact=False)

buf = io.BytesIO()
Image.fromarray(rgba).save(buf, "WEBP", lossless=True, quality=100, method=6, exact=True)
data = buf.getvalue()
back = np.array(Image.open(io.BytesIO(data)).convert("RGBA"))
assert np.array_equal(back, rgba), "lossless WebP round trip failed"

out = os.path.join(os.path.dirname(__file__), "..", "src", "dev", "premultiply-fixture.ts")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/make_premultiply_fixture.py: synthetic test data, do not edit.\n")
    f.write(f"export const PREMULTIPLY_FIXTURE_SIZE = [{W}, {H}] as const;\n")
    f.write(f"export const PREMULTIPLY_FIXTURE_WEBP_BASE64 =\n  '{base64.b64encode(data).decode()}';\n")
    f.write("/** Straight (non-premultiplied) RGBA, row by row from the top. */\n")
    f.write(f"export const PREMULTIPLY_FIXTURE_STRAIGHT_RGBA: readonly number[] = {json.dumps(rgba.reshape(-1).tolist())};\n")
print(f"wrote {os.path.normpath(out)} ({len(data)} bytes of WebP)")
